async function main() {
  const batch = db.batch();
  for (const item of items) {
    const ref = col.doc(item.id);
    const meta = ITEM_CURATION[item.id] ?? {};
    batch.set(ref, {
      name: item.name,
      description: item.description,
      slot: item.slot,
      slotId: item.slotId,
      ageGroups: item.ageGroups,
      defaultFor: item.defaultFor,
      swapOptions: item.swapOptions,
      dollarCostCents: item.dollarCostCents,
      holiday: 'hanukkah',
      imageUrl: null,
      curationTags: meta.curationTags ?? [],
      brand: meta.brand ?? null,
      updatedAt: admin.firestore.FieldValue.serverTimestamp(),
    });
  }
  await batch.commit();
  console.log(`Seeded ${items.length} catalog items under catalog/hanukkah/items`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
